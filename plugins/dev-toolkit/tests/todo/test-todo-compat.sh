#!/usr/bin/env bash
# Тест режимов compat и version скрипта scripts/todo.sh: вердикт совместимости списка задач с форматом
# скрипта на синтетических образцах четырёх видов списков (формат скрипта, чекбоксы, нумерованный список,
# таблицы и разделы) и на частично переведённом списке. Режим только читает: каждый случай сверяет и то,
# что файлы не изменились.
# Запуск из корня репозитория:
#   bash plugins/dev-toolkit/tests/todo/test-todo-compat.sh
# TODO_SH — путь к проверяемому скрипту вместо scripts/todo.sh (для мутационной проверки теста).
set -uo pipefail
unset TODO_FILE TODO_DONE_FILE TODO_COUNTER_FILE

_here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
_sh="$(readlink -f "${TODO_SH:-${_here}/../../scripts/todo.sh}")"
_pass=0
_fail=0
_root="$(mktemp -d)"
trap 'rm -rf "${_root}"' EXIT

# Варианты awk: каталог с симлинком awk первым в PATH. Отсутствующий вариант пропускается и называется.
_awks=()
_skipped=()
for _a in gawk mawk busybox; do
  if command -v "${_a}" >/dev/null 2>&1; then
    _awks+=("${_a}")
  else
    _skipped+=("${_a}")
  fi
done

# ok <имя> <условие-код> — учёт результата проверки.
ok() {
  if [[ "$2" -eq 0 ]]; then
    _pass=$((_pass + 1))
  else
    _fail=$((_fail + 1))
    printf 'FAIL: %s\n' "$1"
  fi
}

# bin_for <вариант awk> — каталог с awk этого варианта; печатает путь.
bin_for() {
  local _d="${_root}/bin-$1" _p
  if [[ ! -d "${_d}" ]]; then
    mkdir -p "${_d}"
    _p="$(command -v "$1")"
    if [[ "$1" == busybox ]]; then
      printf '#!/bin/sh\nexec %s awk "$@"\n' "${_p}" >"${_d}/awk"
      chmod +x "${_d}/awk"
    else
      ln -s "${_p}" "${_d}/awk"
    fi
  fi
  printf '%s' "${_d}"
}

# Каталоги-образцы: в каждом doc/ с файлами списка; функция создаёт и печатает путь. Имя — аргументом:
# вызов идёт в подстановке $(…), счётчик внутри функции до вызывающего не дошёл бы.
sample() {
  local _d="${_root}/$1"
  mkdir -p "${_d}/doc"
  printf '%s' "${_d}"
}

record() {
  printf '### №%s. %s\n- **Приоритет:** средний (владелец, 2026-10-19)\n- **Статус:** открыта\n- **Тип:** задача\n- **Заведено:** 2026-10-19 — решение владельца\n- **Триаж v2:** не находка ревью\n- **Ревью:** high\n\nТекст задачи.\n' "$1" "$2"
}

archive_head() {
  printf '# Архив\n\n## Выполненные задачи\n\n'
}

# run_compat <каталог> <вариант awk> — compat из каталога образца; stdout+stderr в out, код в rc.
run_compat() {
  local _bin
  _bin="$(bin_for "$2")"
  out="$(cd "$1" && PATH="${_bin}:${PATH}" bash "${_sh}" compat 2>&1)"
  rc=$?
}

# snapshot <каталог> — контрольная сумма всех файлов doc/ (для проверки «только чтение»).
snapshot() {
  (cd "$1" && find doc -type f -print0 | sort -z | xargs -0 sha256sum 2>/dev/null; find doc -type l)
}

has() { [[ "${out}" == *"$1"* ]]; }

# --- образцы ---

# 1. Совместимый: формат скрипта, все три файла, шапка с прозой.
s_ok="$(sample s1)"
{
  printf '# TODO\n\nШапка: правила списка.\n\n'
  record 3 'Первая'
  printf '\n'
  record 4 'Вторая'
  # Пункты чужого вида внутри текста записи — часть записи, не строки вне записей.
  printf '1. шаг\n- [ ] подпункт\n| a | b |\n'
} >"${s_ok}/doc/TODO.md"
{
  archive_head
  printf '### №2. Закрытая\n- **Закрыто:** 2026-10-01, PR #5\n- **Итог:** сделано.\n- **Приоритет:** низкий (владелец, 2026-09-01)\n- **Статус:** закрыта\n- **Тип:** задача\n- **Заведено:** 2026-09-01 — решение владельца\n- **Триаж v2:** дефект\n- **Ревью:** low\n\nТекст.\n\n## Прежний формат\n\n- **Задача №1: старая** — сделано.\n'
} >"${s_ok}/doc/TODO-DONE.md"
printf '5 # выдан №4 — Вторая\n' >"${s_ok}/doc/.todo-next"

# 2. Чекбоксы, без архива и счётчика.
s_cb="$(sample s2)"
printf '# TODO\n\n- [ ] **Первое.** текст\n- [x] ~~**Второе.**~~ сделано\n- [ ] **Третье.** текст\n' >"${s_cb}/doc/TODO.md"

# 3. Нумерованный список с номерами-ссылками, без архива и счётчика.
s_num="$(sample s3)"
printf '# TODO\n\n## Активные\n\n4. **Пункт четыре.** текст\n7. ✅ **Пункт семь.** закрыт\n12. **Пункт двенадцать.** текст\n' >"${s_num}/doc/TODO.md"

# 4. Таблицы и разделы ###, без архива и счётчика.
s_tbl="$(sample s4)"
printf '# TODO\n\n## Приоритеты\n\n### Уровень 1\n\n| Пункт | Почему |\n|---|---|\n| ~~**123**~~ | закрыт |\n| **55** | открыт |\n' >"${s_tbl}/doc/TODO.md"

# 5. Частично переведённый: архив и счётчик есть, в списке записи и старые чекбоксы вне записей.
s_mix="$(sample s5)"
{
  printf '# TODO\n\n- [ ] **Старый пункт.** текст\n\n'
  record 8 'Новая'
} >"${s_mix}/doc/TODO.md"
archive_head >"${s_mix}/doc/TODO-DONE.md"
printf '9 # выдан №8 — Новая\n' >"${s_mix}/doc/.todo-next"

# 6. Формат скрипта без счётчика.
s_nocnt="$(sample s6)"
record 2 'Одна' >"${s_nocnt}/doc/TODO.md"
archive_head >"${s_nocnt}/doc/TODO-DONE.md"

# 7. Битый счётчик.
s_badcnt="$(sample s7)"
record 2 'Одна' >"${s_badcnt}/doc/TODO.md"
archive_head >"${s_badcnt}/doc/TODO-DONE.md"
printf 'десять\n' >"${s_badcnt}/doc/.todo-next"

# 8. Ошибка полей: недопустимый тип.
s_field="$(sample s8)"
record 2 'Одна' | sed 's/^- \*\*Тип:\*\* задача$/- **Тип:** эпик/' >"${s_field}/doc/TODO.md"
archive_head >"${s_field}/doc/TODO-DONE.md"
printf '3 # выдан №2 — Одна\n' >"${s_field}/doc/.todo-next"

# 9. Файла списка нет вовсе.
s_none="$(sample s9)"

# 10. Список — символическая ссылка.
s_link="$(sample s10)"
record 2 'Одна' >"${s_link}/doc/real.md"
ln -s real.md "${s_link}/doc/TODO.md"
archive_head >"${s_link}/doc/TODO-DONE.md"
printf '3 # выдан №2 — Одна\n' >"${s_link}/doc/.todo-next"

# 11. Шапка с нумерованными шагами процедуры, записи формата есть — совместим, но с предупреждением.
s_warn="$(sample s11)"
{
  printf '# TODO\n\n## Как выполнять пункт\n\n1. Править JSON.\n2. Собрать.\n\n'
  record 5 'Задача'
} >"${s_warn}/doc/TODO.md"
archive_head >"${s_warn}/doc/TODO-DONE.md"
printf '6 # выдан №5 — Задача\n' >"${s_warn}/doc/.todo-next"

# 12. Список не читается (под root проверка прав не работает — случай пропускается и называется).
s_unread="$(sample s12)"
record 2 'Одна' >"${s_unread}/doc/TODO.md"
archive_head >"${s_unread}/doc/TODO-DONE.md"
printf '3 # выдан №2 — Одна\n' >"${s_unread}/doc/.todo-next"
chmod 000 "${s_unread}/doc/TODO.md"
_root_user=0
[[ "$(id -u)" -eq 0 ]] && _root_user=1

# --- проверки ---

for _a in "${_awks[@]}"; do
  # 1. совместим, код 0, без предупреждений
  _b="$(snapshot "${s_ok}")"
  run_compat "${s_ok}" "${_a}"
  [[ ${rc} -eq 0 ]]
  ok "[${_a}] формат скрипта: код 0" "$?"
  has 'todo compat: совместим'
  ok "[${_a}] формат скрипта: вердикт «совместим»" "$?"
  has 'записей формата: 2' && has 'записей формата: 1'
  ok "[${_a}] формат скрипта: записей списка 2, архива 1" "$?"
  ! has 'предупреждение'
  ok "[${_a}] формат скрипта: нет предупреждения" "$?"
  _now="$(snapshot "${s_ok}")"
  [[ "${_now}" == "${_b}" ]]
  ok "[${_a}] формат скрипта: файлы не изменены" "$?"

  # 2. чекбоксы
  _b="$(snapshot "${s_cb}")"
  run_compat "${s_cb}" "${_a}"
  [[ ${rc} -eq 1 ]]
  ok "[${_a}] чекбоксы: код 1" "$?"
  has 'todo compat: несовместим'
  ok "[${_a}] чекбоксы: вердикт «несовместим»" "$?"
  has 'архив ./doc/TODO-DONE.md: нет файла' && has 'счётчик ./doc/.todo-next: нет файла'
  ok "[${_a}] чекбоксы: названы нет архива и нет счётчика" "$?"
  has 'список ./doc/TODO.md: есть, записей формата: 0'
  ok "[${_a}] чекбоксы: записей формата 0" "$?"
  has 'чекбоксы — 3'
  ok "[${_a}] чекбоксы: строк-чекбоксов вне записей 3" "$?"
  _now="$(snapshot "${s_cb}")"
  [[ "${_now}" == "${_b}" && ! -e "${s_cb}/doc/.todo-next" ]]
  ok "[${_a}] чекбоксы: файлы не изменены, счётчик не создан" "$?"

  # 3. нумерованный — наибольший прежний номер для счётчика
  run_compat "${s_num}" "${_a}"
  [[ ${rc} -eq 1 ]]
  ok "[${_a}] нумерованный: код 1" "$?"
  has 'нумерованные пункты — 3'
  ok "[${_a}] нумерованный: пунктов вне записей 3" "$?"
  has 'наибольший номер в строках вне записей: 12'
  ok "[${_a}] нумерованный: наибольший прежний номер 12" "$?"

  # 4. таблицы и ###
  run_compat "${s_tbl}" "${_a}"
  [[ ${rc} -eq 1 ]]
  ok "[${_a}] таблицы: код 1" "$?"
  has 'строки таблиц — 4'
  ok "[${_a}] таблицы: строк таблиц вне записей 4" "$?"
  has 'doc/TODO.md:5:'
  ok "[${_a}] таблицы: ошибка структуры на строке ###" "$?"
  has 'наибольший номер в строках вне записей: 123'
  ok "[${_a}] таблицы: наибольший прежний номер 123" "$?"

  # 5. частично переведённый — совместим по структуре, предупреждение о чекбоксе
  run_compat "${s_mix}" "${_a}"
  [[ ${rc} -eq 0 ]]
  ok "[${_a}] частичный: код 0" "$?"
  has 'предупреждение' && has 'чекбоксы — 1'
  ok "[${_a}] частичный: предупреждение о строках вне записей" "$?"
  has 'doc/TODO.md:3:'
  ok "[${_a}] частичный: строка названа номером" "$?"

  # 6. нет счётчика
  run_compat "${s_nocnt}" "${_a}"
  [[ ${rc} -eq 1 ]]
  ok "[${_a}] без счётчика: код 1" "$?"
  has 'счётчик ./doc/.todo-next: нет файла' && has 'next'
  ok "[${_a}] без счётчика: подсказка про next" "$?"
  [[ ! -e "${s_nocnt}/doc/.todo-next" ]]
  ok "[${_a}] без счётчика: счётчик не создан" "$?"

  # 7. битый счётчик
  run_compat "${s_badcnt}" "${_a}"
  [[ ${rc} -eq 1 ]]
  ok "[${_a}] битый счётчик: код 1" "$?"
  has 'не в формате «N # выдан №M — название»'
  ok "[${_a}] битый счётчик: причина названа" "$?"

  # 8. ошибка полей
  run_compat "${s_field}" "${_a}"
  [[ ${rc} -eq 1 ]]
  ok "[${_a}] поля: код 1" "$?"
  has '«Тип»: нужно «задача» или «сводный»'
  ok "[${_a}] поля: ошибка «Тип» названа" "$?"

  # 9. нет списка
  run_compat "${s_none}" "${_a}"
  [[ ${rc} -eq 1 ]]
  ok "[${_a}] нет списка: код 1" "$?"
  has 'список ./doc/TODO.md: нет файла'
  ok "[${_a}] нет списка: причина названа" "$?"
  _now="$(ls -A "${s_none}/doc")"
  [[ -z "${_now}" ]]
  ok "[${_a}] нет списка: каталог не изменён" "$?"

  # 10. символическая ссылка
  run_compat "${s_link}" "${_a}"
  [[ ${rc} -eq 1 ]]
  ok "[${_a}] ссылка: код 1" "$?"
  has 'список ./doc/TODO.md: символическая ссылка'
  ok "[${_a}] ссылка: причина названа" "$?"

  # 11. шапка с шагами процедуры — совместим с предупреждением
  run_compat "${s_warn}" "${_a}"
  [[ ${rc} -eq 0 ]]
  ok "[${_a}] шапка с шагами: код 0" "$?"
  has 'предупреждение' && has 'нумерованные пункты — 2'
  ok "[${_a}] шапка с шагами: предупреждение, пунктов 2" "$?"

  # 12. нечитаемый список — несовместим с причиной, а не падение разбора
  if [[ "${_root_user}" -eq 0 ]]; then
    run_compat "${s_unread}" "${_a}"
    [[ ${rc} -eq 1 ]]
    ok "[${_a}] нечитаемый список: код 1" "$?"
    has 'список ./doc/TODO.md: не читается'
    ok "[${_a}] нечитаемый список: причина названа" "$?"
  fi
done
chmod 644 "${s_unread}/doc/TODO.md"
if [[ "${_root_user}" -eq 1 ]]; then
  _skipped+=('нечитаемый список (под root)')
fi

# version: одна строка «todo.sh <версия>», версия — semver, код 0.
_v="$(bash "${_sh}" version 2>&1)" || true
[[ "${_v}" =~ ^todo\.sh\ [0-9]+\.[0-9]+\.[0-9]+$ ]]
ok "version: формат «todo.sh X.Y.Z»" "$?"

_note=''
if [[ ${#_skipped[@]} -gt 0 ]]; then
  _note=" (нет на машине и пропущены: ${_skipped[*]})"
fi
printf 'compat/version: %d прошло, %d упало; awk: %s%s\n' "${_pass}" "${_fail}" "${_awks[*]}" "${_note}"
[[ "${_fail}" -eq 0 ]]
