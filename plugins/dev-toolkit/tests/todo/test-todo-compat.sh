#!/usr/bin/env bash
# Тест режимов compat и version скрипта scripts/todo.sh: вердикт совместимости списка задач с форматом
# скрипта на синтетических образцах четырёх видов списков (формат скрипта, чекбоксы, нумерованный список,
# таблицы и разделы), на частично переведённом списке и на нарушениях, которые судят check, new и close (код 1 —
# список не переведён, код 3 — список в формате с нарушениями). Режим только читает: каждый случай сверяет и то, что
# файлы не изменились.
# Запуск из корня репозитория:
#   bash plugins/dev-toolkit/tests/todo/test-todo-compat.sh
# Переменные:
#   TODO_SH=<путь>   проверяемый скрипт вместо scripts/todo.sh (мутационная проверка теста);
#   TODO_AWKS="…"    только названные варианты awk (через пробел: системный mawk gawk busybox).
set -uo pipefail
export LC_ALL=C
unset TODO_FILE TODO_DONE_FILE TODO_COUNTER_FILE

_here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
_sh="$(readlink -f "${TODO_SH:-${_here}/../../scripts/todo.sh}")"
_pass=0
_fail=0
_root="$(mktemp -d)"
trap 'chmod -R u+rwx "${_root}" 2>/dev/null; rm -rf "${_root}"' EXIT

# Варианты awk — как в test-todo.sh: системный awk и симлинк «awk» каждого найденного варианта в каталоге
# первым в PATH (busybox — обёрткой). Отсутствующий вариант пропускается и называется в итоге.
_awk_names=('системный')
_awk_paths=("${PATH}")
_skipped=()
for _a in mawk gawk busybox; do
  if ! _p="$(command -v "${_a}" 2>/dev/null)"; then
    _skipped+=("${_a}")
    continue
  fi
  mkdir -p "${_root}/.bin-${_a}"
  if [[ "${_a}" == busybox ]]; then
    printf '#!/bin/sh\nexec %s awk "$@"\n' "${_p}" >"${_root}/.bin-${_a}/awk"
    chmod +x "${_root}/.bin-${_a}/awk"
  else
    ln -s "${_p}" "${_root}/.bin-${_a}/awk"
  fi
  _awk_names+=("${_a}")
  _awk_paths+=("${_root}/.bin-${_a}:${PATH}")
done
_sel_names=()
_sel_paths=()
for _i in "${!_awk_names[@]}"; do
  if [[ -z "${TODO_AWKS:-}" || " ${TODO_AWKS} " == *" ${_awk_names[_i]} "* ]]; then
    _sel_names+=("${_awk_names[_i]}")
    _sel_paths+=("${_awk_paths[_i]}")
  fi
done
if [[ ${#_sel_names[@]} -eq 0 ]]; then
  printf 'FAIL: TODO_AWKS="%s" не выбрал ни одного варианта awk (есть: %s)\n' "${TODO_AWKS:-}" "${_awk_names[*]}"
  exit 1
fi

# ok <имя> <условие-код> — учёт результата проверки.
ok() {
  if [[ "$2" -eq 0 ]]; then
    _pass=$((_pass + 1))
  else
    _fail=$((_fail + 1))
    printf 'FAIL: %s\n' "$1"
  fi
}

# Каталоги-образцы: в каждом doc/ с файлами списка; функция создаёт и печатает путь. Имя — аргументом:
# вызов идёт в подстановке $(…), счётчик внутри функции до вызывающего не дошёл бы.
sample() {
  local _d="${_root}/$1"
  mkdir -p "${_d}/doc"
  printf '%s' "${_d}"
}

record() {
  printf '### №%s. %s\n- **Приоритет:** средний (владелец, 2026-10-19)\n- **Статус:** открыта\n- **Тип:** задача\n- **Заведено:** 2026-10-19 — решение владельца\n- **Триаж v2:** не находка ревью\n- **Ревью:** high\n\nТекст задачи.\n' "$1" "$2"
}

archive_head() {
  printf '# Архив\n\n## Выполненные задачи\n\n'
}

# snapshot <каталог> — контрольная сумма читаемых файлов doc/, тип и права всех путей (для проверки «только
# чтение»). Без sha256sum снимок был бы пуст и сравнение — пустым: тогда стенд падает.
snapshot() {
  (cd "$1" && find doc -type f -readable -print0 | sort -z | xargs -0 -r sha256sum && find doc -printf '%y %m %p\n' | sort)
}
command -v sha256sum >/dev/null 2>&1 || {
  printf 'FAIL: нет sha256sum — проверка «файлы не изменены» невозможна\n'
  exit 1
}

# run_compat <каталог> [аргументы до compat…] — compat из каталога образца под текущим вариантом awk;
# stdout+stderr в out, код в rc; same=0, если файлы образца не изменились (это и отдельная проверка — в каждом
# вызове).
run_compat() {
  local _dir="$1" _before _after
  shift
  _before="$(snapshot "${_dir}")"
  out="$(cd "${_dir}" && PATH="${_awkpath}" timeout 60 bash "${_sh}" "$@" compat 2>&1)"
  rc=$?
  _after="$(snapshot "${_dir}")"
  [[ "${_after}" == "${_before}" ]]
  same=$?
  ok "[${_a}] ${_dir##*/} ${*:+($*) }compat: файлы не изменены" "${same}"
}

has() { [[ "${out}" == *"$1"* ]]; }

