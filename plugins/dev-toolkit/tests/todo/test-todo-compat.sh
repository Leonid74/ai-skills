# --- проверки ---

for _i in "${!_sel_names[@]}"; do
  _a="${_sel_names[_i]}"
  _awkpath="${_sel_paths[_i]}"

  # 1. совместим, код 0, без предупреждений
  run_compat "${s_ok}"
  [[ ${rc} -eq 0 ]]
  ok "[${_a}] формат скрипта: код 0" "$?"
  has 'todo compat: совместим'
  ok "[${_a}] формат скрипта: вердикт «совместим»" "$?"
  has 'записей формата: 2' && has 'записей формата: 1'
  ok "[${_a}] формат скрипта: записей списка 2, архива 1" "$?"
  has 'счётчик ./doc/.todo-next: есть, следующий номер 5'
  ok "[${_a}] формат скрипта: следующий номер 5" "$?"
  ! has 'предупреждение' && ! has 'наибольший номер'
  ok "[${_a}] формат скрипта: нет предупреждения и совета о номере" "$?"

  # 2. чекбоксы
  run_compat "${s_cb}"
  [[ ${rc} -eq 1 ]]
  ok "[${_a}] чекбоксы: код 1" "$?"
  has 'todo compat: несовместим'
  ok "[${_a}] чекбоксы: вердикт «несовместим»" "$?"
  has 'архив ./doc/TODO-DONE.md: нет файла' && has 'счётчик ./doc/.todo-next: нет файла'
  ok "[${_a}] чекбоксы: названы нет архива и нет счётчика" "$?"
  has 'список ./doc/TODO.md: есть, записей формата: 0'
  ok "[${_a}] чекбоксы: записей формата 0" "$?"
  has 'чекбоксы — 5'
  ok "[${_a}] чекбоксы: строк-чекбоксов вне записей 5 (с маркерами «*» и «+»)" "$?"
  [[ ${same} -eq 0 && ! -e "${s_cb}/doc/.todo-next" ]]
  ok "[${_a}] чекбоксы: файлы не изменены, счётчик не создан" "$?"

  # 3. нумерованный — наибольший прежний номер для счётчика
  run_compat "${s_num}"
  [[ ${rc} -eq 1 ]]
  ok "[${_a}] нумерованный: код 1" "$?"
  has 'нумерованные пункты — 3'
  ok "[${_a}] нумерованный: пунктов вне записей 3" "$?"
  has 'наибольший номер в строках вне записей: 12 ('
  ok "[${_a}] нумерованный: наибольший прежний номер 12" "$?"

  # 4. таблицы и ###
  run_compat "${s_tbl}"
  [[ ${rc} -eq 1 ]]
  ok "[${_a}] таблицы: код 1" "$?"
  has 'строки таблиц — 4'
  ok "[${_a}] таблицы: строк таблиц вне записей 4" "$?"
  has 'doc/TODO.md:5:'
  ok "[${_a}] таблицы: ошибка структуры на строке ###" "$?"
  has 'наибольший номер в строках вне записей: 123 ('
  ok "[${_a}] таблицы: наибольший прежний номер 123" "$?"

  # 5. частично переведённый — совместим по структуре, предупреждение о чекбоксе
  run_compat "${s_mix}"
  [[ ${rc} -eq 0 ]]
  ok "[${_a}] частичный: код 0" "$?"
  has 'предупреждение' && has 'чекбоксы — 1'
  ok "[${_a}] частичный: предупреждение о строках вне записей" "$?"
  has 'doc/TODO.md:3:'
  ok "[${_a}] частичный: строка названа номером" "$?"

  # 6. нет счётчика — совместим, предупреждение: next создаст счётчик
  run_compat "${s_nocnt}"
  [[ ${rc} -eq 0 ]]
  ok "[${_a}] без счётчика: код 0" "$?"
  has 'todo compat: совместим'
  ok "[${_a}] без счётчика: вердикт «совместим»" "$?"
  has 'предупреждение: счётчик ./doc/.todo-next: нет файла — next создаст его'
  ok "[${_a}] без счётчика: предупреждение и подсказка про next" "$?"
  [[ ${same} -eq 0 && ! -e "${s_nocnt}/doc/.todo-next" ]]
  ok "[${_a}] без счётчика: файлы не изменены, счётчик не создан" "$?"

  # 7. битый счётчик
  run_compat "${s_badcnt}"
  [[ ${rc} -eq 3 ]]
  ok "[${_a}] битый счётчик: код 3 — нарушения формата" "$?"
  has 'не в формате «N # выдан №M — название»'
  ok "[${_a}] битый счётчик: причина названа" "$?"
  has 'todo compat: нарушения формата — список уже в формате (записей: 1)' && ! has 'несовместим'
  ok "[${_a}] битый счётчик: вердикт «нарушения формата», не «несовместим»" "$?"

  # 8. ошибка полей
  run_compat "${s_field}"
  [[ ${rc} -eq 3 ]]
  ok "[${_a}] поля: код 3 — нарушения формата" "$?"
  has '«Тип»: нужно «задача» или «сводный»'
  ok "[${_a}] поля: ошибка «Тип» названа" "$?"

  # 9. нет списка
  run_compat "${s_none}"
  [[ ${rc} -eq 1 ]]
  ok "[${_a}] нет списка: код 1" "$?"
  has 'список ./doc/TODO.md: нет файла'
  ok "[${_a}] нет списка: причина названа" "$?"
  _now="$(ls -A "${s_none}/doc")"
  [[ -z "${_now}" ]]
  ok "[${_a}] нет списка: каталог не изменён" "$?"

  # 10. символическая ссылка
  run_compat "${s_link}"
  [[ ${rc} -eq 1 ]]
  ok "[${_a}] ссылка: код 1" "$?"
  has 'список ./doc/TODO.md: символическая ссылка'
  ok "[${_a}] ссылка: причина названа" "$?"

  # 11. шапка с шагами процедуры — совместим с предупреждением
  run_compat "${s_warn}"
  [[ ${rc} -eq 0 ]]
  ok "[${_a}] шапка с шагами: код 0" "$?"
  has 'предупреждение' && has 'нумерованные пункты — 2'
  ok "[${_a}] шапка с шагами: предупреждение, пунктов 2" "$?"

  # 12. нечитаемый список — несовместим с причиной, а не падение разбора
  if [[ "${_root_user}" -eq 0 ]]; then
    run_compat "${s_unread}"
    [[ ${rc} -eq 1 ]]
    ok "[${_a}] нечитаемый список: код 1" "$?"
    has 'список ./doc/TODO.md: не читается'
    ok "[${_a}] нечитаемый список: причина названа" "$?"
  fi

  # 13. большой прежний список — вердикт и обрезка вывода до пяти строк
  run_compat "${s_big}"
  [[ ${rc} -eq 1 ]]
  ok "[${_a}] большой список: код 1, а не обрыв (${rc})" "$?"
  has 'todo compat: несовместим'
  ok "[${_a}] большой список: вердикт напечатан" "$?"
  has 'всего таких строк: 700'
  ok "[${_a}] большой список: названо число строк" "$?"
  _shown="$(grep -c '^\./doc/TODO\.md:[0-9]*: чекбоксы: ' <<<"${out}")"
  [[ "${_shown}" -eq 5 ]]
  ok "[${_a}] большой список: показано 5 строк (${_shown})" "$?"
  has 'наибольший номер в строках вне записей: 700 ('
  ok "[${_a}] большой список: наибольший прежний номер 700" "$?"

  # 14. счётчик — каталог
  run_compat "${s_cntdir}"
  [[ ${rc} -eq 3 ]]
  ok "[${_a}] счётчик-каталог: код 3 — нарушения формата" "$?"
  has 'счётчик ./doc/.todo-next: не обычный файл'
  ok "[${_a}] счётчик-каталог: причина названа" "$?"

  # 15. счётчик не больше наибольшего номера — как в check
  run_compat "${s_low}"
  [[ ${rc} -eq 3 ]]
  ok "[${_a}] низкий счётчик: код 3 — нарушения формата" "$?"
  has 'следующий номер 2 не больше наибольшего занятого (2)'
  ok "[${_a}] низкий счётчик: причина названа" "$?"

  # 16. повтор номера — как в check
  run_compat "${s_dup}"
  [[ ${rc} -eq 3 ]]
  ok "[${_a}] повтор номера: код 3 — нарушения формата" "$?"
  has '№2: номер встречается больше одного раза'
  ok "[${_a}] повтор номера: причина названа" "$?"

  # 17. нет перевода строки в конце — new и close откажут
  run_compat "${s_nonl}"
  [[ ${rc} -eq 3 ]]
  ok "[${_a}] без перевода строки: код 3 — нарушения формата" "$?"
  has 'список ./doc/TODO.md: файл пуст или не кончается переводом строки'
  ok "[${_a}] без перевода строки: причина названа" "$?"

  # 18–19. архив, куда close не вставит запись
  run_compat "${s_nogap}"
  [[ ${rc} -eq 3 ]]
  ok "[${_a}] архив без пустой строки: код 3 — нарушения формата" "$?"
  has 'после первого заголовка раздела нет пустой строки'
  ok "[${_a}] архив без пустой строки: причина названа" "$?"
  run_compat "${s_noh2}"
  [[ ${rc} -eq 3 ]]
  ok "[${_a}] архив без раздела: код 3 — нарушения формата" "$?"
  has 'нет заголовка раздела (## …)'
  ok "[${_a}] архив без раздела: причина названа" "$?"

  # 20. ошибка полей в архиве
  run_compat "${s_afield}"
  [[ ${rc} -eq 3 ]]
  ok "[${_a}] поля архива: код 3 — нарушения формата" "$?"
  has 'TODO-DONE.md' && has '«Тип»: нужно «задача» или «сводный»'
  ok "[${_a}] поля архива: ошибка названа" "$?"

  # 21. формы номера прежнего пункта (файл образца переписывается по ходу случая — сначала исходный)
  # shellcheck disable=SC2059
  printf "${FORMS}" >"${s_forms}/doc/TODO.md"
  run_compat "${s_forms}"
  has 'наибольший номер в строках вне записей: 44 ('
  ok "[${_a}] формы номера: «№44» — наибольший; 9999, 2026 и жирное число без точки — не номер" "$?"
  has 'нумерованные пункты — 1' && has 'чекбоксы — 4' && has 'строки таблиц — 1'
  ok "[${_a}] формы номера: «- **42.**» — нумерованный пункт" "$?"
  printf '# TODO\n\n- [ ] 41. чекбокс с номером\n- **42.** жирный номер\n| 43 | таблица |\n' >"${s_forms}/doc/TODO.md"
  run_compat "${s_forms}"
  has 'наибольший номер в строках вне записей: 43 ('
  ok "[${_a}] формы номера: «| 43 |» в начале строки таблицы" "$?"
  printf '# TODO\n\n- [ ] 41. чекбокс с номером\n- **42.** жирный номер\n' >"${s_forms}/doc/TODO.md"
  run_compat "${s_forms}"
  has 'наибольший номер в строках вне записей: 42 ('
  ok "[${_a}] формы номера: «- **42.**»" "$?"
  printf '# TODO\n\n- [ ] 41. чекбокс с номером\n' >"${s_forms}/doc/TODO.md"
  run_compat "${s_forms}"
  has 'наибольший номер в строках вне записей: 41 ('
  ok "[${_a}] формы номера: «- [ ] 41.»" "$?"
  run_compat "${s_form137}"
  has 'наибольший номер в строках вне записей: 137 ('
  ok "[${_a}] формы номера: «### 137.»" "$?"
  # Не номер: дата и дробь в начале строки, строка с отступом, число длиннее 9 цифр, ячейка «90 мая» — любая из них
  # подняла бы наибольший номер выше 8.
  printf '# TODO\n\n- [ ] 8. малый\n19.10.2026 — созвон\n30.5 ГБ\n2026.10.19 релиз\n  77. продолжение с отступом\n12345678901234567890. огромное\n| 90 мая | событие |\n' >"${s_forms}/doc/TODO.md"
  run_compat "${s_forms}"
  has 'наибольший номер в строках вне записей: 8 ('
  ok "[${_a}] формы номера: дата, дробь, отступ, 20 цифр, «90 мая» — не номер" "$?"
  # Нумерованный пункт с маркером и со скобкой.
  printf '# TODO\n\n- 45. маркированный\n* 46) звезда со скобкой\n12) скобка\n' >"${s_forms}/doc/TODO.md"
  run_compat "${s_forms}"
  has 'нумерованные пункты — 3' && has 'наибольший номер в строках вне записей: 46 ('
  ok "[${_a}] формы номера: «- 45.», «* 46)», «12)» — нумерованные пункты" "$?"

  # 22. номера прежних пунктов архива выше счётчика — совместим с предупреждением
  run_compat "${s_oldarch}"
  [[ ${rc} -eq 0 ]]
  ok "[${_a}] прежние номера архива: код 0" "$?"
  has 'наибольший номер в строках вне записей: 57 ('
  ok "[${_a}] прежние номера архива: номер 57 учтён" "$?"
  has 'предупреждение: следующий номер счётчика 3 не больше наибольшего номера вне записей (57)'
  ok "[${_a}] прежние номера архива: предупреждение о счётчике" "$?"

  # 23. управляющие символы и многобайтовые символы в выводе
  run_compat "${s_ctrl}"
  [[ "${out}" != *$'\033'* && "${out}" != *$'\007'* ]]
  ok "[${_a}] управляющие символы: ESC и BEL не выводятся" "$?"
  iconv -f UTF-8 -t UTF-8 <<<"${out}" >/dev/null 2>&1
  ok "[${_a}] управляющие символы: вывод — корректный UTF-8" "$?"

  # 25. архив без перевода в формат: проверки списка по отдельности
  run_compat "${s_one}"
  [[ ${rc} -eq 1 ]]
  ok "[${_a}] без архива: код 1" "$?"
  has 'doc/TODO.md:3:' && has '«Тип»: нужно «задача» или «сводный»'
  ok "[${_a}] без архива: названы и ошибка структуры, и ошибка поля" "$?"

  # 26. заголовок раздела последней строкой архива — нарушение; шаблон со вторым разделом — совместим
  run_compat "${s_lasth}"
  [[ ${rc} -eq 3 ]]
  ok "[${_a}] заголовок последней строкой: код 3" "$?"
  has 'первый заголовок раздела — последняя строка файла'
  ok "[${_a}] заголовок последней строкой: причина названа" "$?"
  run_compat "${s_tmpl}"
  [[ ${rc} -eq 0 ]]
  ok "[${_a}] шаблон архива со вторым разделом: код 0" "$?"

  # 27. чужой список с архивом и нарушением — несовместим, а не «нарушения формата»
  run_compat "${s_foreign}"
  [[ ${rc} -eq 1 ]] && has 'todo compat: несовместим'
  ok "[${_a}] чужой список при архиве: код 1, «несовместим»" "$?"

  # 24. метка файла — по роли, а не по совпадению пути: счётчик по пути (отсутствующего) списка
  run_compat "${s_none}" --counter doc/TODO.md
  has 'список ./doc/TODO.md: нет файла' && has 'предупреждение: счётчик ./doc/TODO.md: нет файла'
  ok "[${_a}] метка по роли: счётчик назван счётчиком" "$?"
done
chmod 644 "${s_unread}/doc/TODO.md"
if [[ "${_root_user}" -eq 1 ]]; then
  _skipped+=('нечитаемый список (под root)')
fi

